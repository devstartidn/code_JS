let a = 10;
let b = 5;

console.log(a + b); //tamabah
console.log(a - b); //kurang
console.log(a * b); //kali
console.log(a / b); //bagi
console.log(a % b); //modulo 

// Nah, yang terakhir ada operator %. 
// Walaupun simbolnya terlihat seperti persen, di JavaScript operator ini disebut modulus, 
// yaitu untuk mendapatkan sisa dari hasil pembagian."

