let skor = 50;
skor += 10;

console.log(skor);

// Nah, sekarang kita punya skor awal 50. Saya ingin menambahkan 10 ke skor tersebut. 
// Kita sebenarnya bisa menulis skor = skor + 10, tetapi JavaScript menyediakan cara yang lebih singkat yaitu skor += 10. 
// Jadi maksudnya adalah ambil nilai skor yang sekarang, tambahkan 10, kemudian simpan kembali hasilnya ke variabel skor