let nama = "Sulthan";
let umur = 20;

console.log(nama);
console.log(umur);

// Sekarang kita masuk ke variabel. 
// Variabel itu bisa kita bayangkan seperti sebuah wadah untuk menyimpan data. 
// Misalnya saya punya wadah bernama nama, kemudian saya masukkan data Sulthan ke dalamnya. 
// Lalu saya punya wadah bernama umur, dan saya masukkan angka 20."

// "Di JavaScript kita bisa membuat wadah tersebut menggunakan let. 
// Jadi let nama = 'Sulthan' artinya kita membuat variabel bernama nama dan memberikan nilai Sulthan ke dalamnya."

// "Setelah datanya disimpan, kita bisa menggunakan variabel tersebut berkali-kali. 
// Contohnya di sini saya menggunakan console.log(nama), 
// maka JavaScript akan mengambil isi dari variabel nama dan menampilkannya di Console