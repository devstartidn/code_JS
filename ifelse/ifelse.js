let nilai = 80;

if (nilai >= 75) {
    console.log("Lulus");
} else {
    console.log("Tidak Lulus");
}

// "Tadi kita sudah belajar comparison operator. 
// JavaScript bisa membandingkan apakah nilai 80 lebih besar atau sama dengan 75 dan menghasilkan true atau false. 
// Sekarang kita gunakan hasil tersebut untuk mengambil keputusan."

// "Kalau kondisinya benar, JavaScript menjalankan bagian if. 
// Kalau kondisinya salah, JavaScript menjalankan bagian else."